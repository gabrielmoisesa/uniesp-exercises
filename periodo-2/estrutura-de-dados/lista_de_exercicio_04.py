def maior_valor(lista: list) -> int:
  maior_valor = lista[0]

  for valor in lista[1:]:
    if valor > maior_valor:
      maior_valor = valor

  return maior_valor

def menor_valor(lista: list) -> int:
  menor_valor = lista[0]

  for valor in lista[1:]:
    if valor < menor_valor:
      menor_valor = valor

  return menor_valor

