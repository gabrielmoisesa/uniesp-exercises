def select_sort(vetor):

  n=len(vetor)

  for i in range(n):
    id_min=i
    for j in range(i+1,n):
      if vetor[id_min]>vetor[j]:
        id_min=j

    aux=vetor[i]
    vetor[i]=vetor[id_min]
    vetor[id_min]=aux

  return (vetor)

