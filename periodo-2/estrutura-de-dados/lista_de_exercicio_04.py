def remover_duplicados(lista: list) -> list:
  lista_formatada = lista

  for valor in lista_formatada:
    contador_valor = 0

    for i in range(len(lista_formatada)):
      if lista_formatada[i] == valor:
        contador_valor += 1

      if contador_valor > 1:
        lista_formatada.pop(i)
        contador_valor -= 1

  return lista_formatada

vetor = [1, 2, 4, 2, 1]
print(remover_duplicados(vetor))

