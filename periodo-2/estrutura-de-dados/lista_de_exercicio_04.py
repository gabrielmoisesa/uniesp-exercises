def contador_pares_impares(lista: list) -> dict:
  contador = {
      "pares": 0,
      "impares": 0
  }

  for valor in lista:
    if valor % 2 == 0:
      contador["pares"] += 1
    else:
      contador["impares"] += 1

  return contador

