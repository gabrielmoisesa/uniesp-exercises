class PilhaEditorTexto:
  def __init__(self) -> None:
    self.texto = []
    self.desfeito = str

  def inserir_texto(self, texto: str):
    self.texto += [texto]

  def desfazer(self):
    self.desfeito = self.texto.pop()

  def refazer(self):
    if isinstance(self.desfeito, str):
      self.inserir_texto(self.desfeito)
    else:
      print("Não há alterações para refazer.")

