class PilhaLeitorOperador:
  def __init__(self) -> None:
    self.expressoes = []

  def inserir_expressao(self, expressao: str) -> None:
    self.expressoes += [expressao]

  def obter_operadores(self) -> list[str]:
    operadores_totais = []

    for expressao in self.expressoes:
      operadores = []

      for char in expressao:
        if char in ("+", "-", "*", "/", "%", "^"):
          operadores.append(char)

      operadores_totais.append(operadores)

    return operadores_totais

  def imprimir_operadores(self) -> None:
    print(f"Operadores: {self.obter_operadores()}")

leitor_operador = PilhaLeitorOperador()
leitor_operador.inserir_expressao("(2+3)*(8-9)/(7^3)")
leitor_operador.inserir_expressao("(5-1)/(1*2)")

leitor_operador.imprimir_operadores()

