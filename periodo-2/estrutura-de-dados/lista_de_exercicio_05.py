class PilhaNavegador:
  def __init__(self) -> None:
    self.historico_paginas = []
    self.pagina_atual = "nova aba"

  def inserir_paginas(self, novas_paginas: list) -> None:
    self.historico_paginas += novas_paginas

  def avancar(self) -> None:
    if self.pagina_atual == "nova aba":
      self.pagina_atual = self.historico_paginas[0]
    else:
      index_pagina_atual = self.historico_paginas.index(self.pagina_atual)

      if index_pagina_atual < len(self.historico_paginas) - 1:
        self.pagina_atual = self.historico_paginas[index_pagina_atual + 1]
      else:
        print(f"Você já está na última página: {self.pagina_atual}")

  def voltar(self) -> None:
    if self.pagina_atual == "nova aba":
      print(f"Não há páginas anteriores. Você está na nova aba: {self.pagina_atual}")
    else:
      index_pagina_atual = self.historico_paginas.index(self.pagina_atual)

      if index_pagina_atual > 0:
        self.pagina_atual = self.historico_paginas[index_pagina_atual - 1]
      else:
        print(f"Você já está na primeira página: {self.pagina_atual}")

