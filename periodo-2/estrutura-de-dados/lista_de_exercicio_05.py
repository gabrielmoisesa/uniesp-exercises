class PilhaCalculadoraRPN:
  def __init__(self) -> None:
    self.expressao = []

  def inserir_expressão(self, expressao: list[float, str]):
    self.expressao += expressao

  def calcular(self) -> float:
    operandos = []

    for valor in self.expressao:
      if isinstance(valor, (int, float)):
        operandos.append(valor)
      elif isinstance(valor, str):
        operando2 = operandos.pop()
        operando1 = operandos.pop()

        if valor == "+":
          operandos.append(operando1 + operando2)
        elif valor == "-":
          operandos.append(operando1 - operando2)
        elif valor == "*":
          operandos.append(operando1 * operando2)
        elif valor == "/":
          operandos.append(operando1 / operando2)
        else:
          print(f"O operador '{valor}' é inválido")

    return operandos[0]

calculadora = PilhaCalculadoraRPN()

calculadora.inserir_expressão([3.0, 4.0, "+", 2.0, "*"])

print(calculadora.calcular())

