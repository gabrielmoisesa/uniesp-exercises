class PilhaLeitorPalindromo:
  def __init__(self) -> None:
    self.palavra = str
    self.palavra_caracteres = []

  def inserir_palavra(self, palavra: str) -> None:
    self.palavra = palavra

  def empilhar_caracteres(self) -> None:
    for char in self.palavra:
      self.palavra_caracteres.append(char)

  def eh_palindromo(self) -> bool:
    self.empilhar_caracteres()
    palavra_caracteres_reverso = list(reversed(self.palavra_caracteres))

    return palavra_caracteres_reverso == self.palavra_caracteres

  def imprimir_eh_palindromo(self) -> None:
    print(f"A palavra '{self.palavra}' {"é" if self.eh_palindromo() else "não é"} um palíndromo.")

