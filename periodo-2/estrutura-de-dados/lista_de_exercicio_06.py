dias = ["Segunda", "Terça", "Quarta", "Quinta", "Sexta"]
semanas = ["S1", "S2", "S3", "S4"]

matriz_semana = [[8, 6, 7, 8, 6],
                 [5, 5, 6, 7, 8],
                 [6, 7, 8, 6, 5],
                 [7, 5, 9, 7, 4]]

total_por_dia = [0] * len(dias)

for i in range(len(semanas)):
    for j in range(len(dias)):
        total_por_dia[j] += matriz_semana[i][j]

total_por_semana = [sum(linha) for linha in matriz_semana]
total_mes = sum(total_por_semana)

menor = min(min(linha) for linha in matriz_semana)
maior = max(max(linha) for linha in matriz_semana)

qtd_menor = sum(linha.count(menor) for linha in matriz_semana)
qtd_maior = sum(linha.count(maior) for linha in matriz_semana)

# 1.
maior_dia = max(total_por_dia)

print("Dia com maior descanso:")
for j in range(len(dias)):
    if total_por_dia[j] == maior_dia:
        print(f"{dias[j]} ({maior_dia}h no mês)")

# 2.
menor_dia = min(total_por_dia)

print("Dia com menor descanso:")
for j in range(len(dias)):
    if total_por_dia[j] == menor_dia:
        print(f"{dias[j]} ({menor_dia}h no mês)")

# 3.
maior_sem = max(total_por_semana)

print("Semana com maior descanso:")
for i in range(len(semanas)):
    if total_por_semana[i] == maior_sem:
        print(f"{semanas[i]} ({maior_sem}h)")

# 4.
menor_sem = min(total_por_semana)

print("Semana com menor descanso:")
for i in range(len(semanas)):
    if total_por_semana[i] == menor_sem:
        print(f"{semanas[i]} ({menor_sem}h)")

# 5.
print(f"Menor tempo de descanso: {menor}h")

# 6.
print(f"Maior tempo de descanso: {maior}h")

# 7.
print(f"Dias com o menor tempo ({menor}h): {qtd_menor}")

# 8.
print(f"Dias com o maior tempo ({maior}h): {qtd_maior}")

# 9.
print("Percentual por semana em relação ao total do mês:")
for i in range(len(semanas)):
    percentual = total_por_semana[i] / total_mes * 100
    print(f"{semanas[i]}: {percentual:.2f}%")